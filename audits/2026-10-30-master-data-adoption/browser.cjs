const {chromium}=require(process.cwd()+'/app/node_modules/playwright');
const fs=require('fs');
const assert=require('assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const errors=[];
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8766/#evaluation-core');
 await page.locator('[data-evaluation="annual"]').waitFor({timeout:60000});
 const family=page.locator('[data-family="master-data-java-spring"]');
 assert.equal(await family.count(),1,'Family must have a single detailed presentation');
 assert.equal(await family.locator('tbody tr').count(),9);
 const clean=s=>s.replace(/\s/g,'');
 assert.ok(clean(await family.innerText()).includes('1500JH'));
 assert.ok(clean(await family.innerText()).includes('17mois'));
 assert.ok(clean(await page.locator('[data-evaluation="core"]').innerText()).includes('6/88'));
 await family.locator('h3').scrollIntoViewIfNeeded();
 await page.screenshot({path:'audits/2026-10-30-master-data-adoption/desktop.png'});
 await family.locator('table').scrollIntoViewIfNeeded();
 await page.screenshot({path:'audits/2026-10-30-master-data-adoption/roles.png'});
 await page.setViewportSize({width:390,height:844});
 await family.locator('h3').scrollIntoViewIfNeeded();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'Mobile horizontal page overflow');
 await page.screenshot({path:'audits/2026-10-30-master-data-adoption/mobile.png'});
 const selector=page.locator('.core-work-trace select').first();
 await selector.selectOption('dotnet');
 assert.equal(await page.locator('[data-family]').count(),0);
 await selector.selectOption('java-spring');
 const cap=page.locator('.core-work-trace select').nth(1);
 await cap.selectOption('BC-002');
 assert.ok((await page.locator('.economic-capacity-work').innerText()).includes('sans ventilation arbitraire'));
 await cap.selectOption('BC-008');
 assert.ok((await page.locator('.economic-capacity-work').innerText()).includes('reste à réestimer'));
 assert.deepEqual(errors,[]);
 const health=await(await fetch('http://127.0.0.1:8766/api/health')).json();
 assert.equal(health.sources_current,true);
 fs.writeFileSync('audits/2026-10-30-master-data-adoption/browser-check.json',JSON.stringify({status:'passed',roles:9,unique_family:true,mobile_overflow:false,capacity_membership_checked:true,health,errors},null,2));
 await browser.close();
 console.log('Local browser checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
